static ENGLISH: AtomicBool = AtomicBool::new(true);
pub fn install(language: Language) {
    ENGLISH.store(language == Language::English, Ordering::Relaxed);
}
pub fn is_english() -> bool { ENGLISH.load(Ordering::Relaxed) }
pub fn current() -> Language {
    if is_english() { Language::English } else { Language::German }
}
pub fn text(source: &str) -> &str { current().text(source) }

// Both format strings remain literal, so Rust checks placeholders and format specifications.
#[macro_export]
macro_rules! tr_format {
    ($de:literal, $en:literal $(, $($args:tt)*)?) => {
        if $crate::i18n::is_english() {
            format!($en $(, $($args)*)?)
        } else {
            format!($de $(, $($args)*)?)
        }
    };
}

