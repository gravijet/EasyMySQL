// Redis: jede Zeile wird ein Hash "tabelle:schluessel"

/// Schluessel einer Zeile: Tabelle und Primaerschluessel (sonst Zeilennummer)
pub fn redis_key(t: &TableInfo, vals: &[Value], n: u64) -> String {
    let pk: Vec<String> = t.columns.iter().zip(vals).filter(|(c, _)| c.is_pk()).filter_map(|(_, v)| text(v)).collect();
    if pk.is_empty() { format!("{}:{n}", t.name) } else { format!("{}:{}", t.name, pk.join(":")) }
}

fn redis_fields(cols: &[mysql::Column], vals: &[Value]) -> Vec<(Vec<u8>, Vec<u8>)> {
    cols.iter()
        .zip(vals)
        .filter_map(|(c, v)| {
            let s = match v {
                Value::NULL => return None,
                Value::Bytes(b) => b.clone(),
                other => crate::db::value_to_string(other)?.into_bytes(),
            };
            Some((c.name_str().into_owned().into_bytes(), s))
        })
        .collect()
}

/// Wert fuer die Befehlsdatei in redis-cli-Schreibweise
pub fn redis_quote(b: &[u8]) -> String {
    let mut o = String::from("\"");
    for &c in b {
        match c {
            b'"' => o.push_str("\\\""),
            b'\\' => o.push_str("\\\\"),
            b'\n' => o.push_str("\\n"),
            b'\r' => o.push_str("\\r"),
            b'\t' => o.push_str("\\t"),
            0x20..=0x7E => o.push(c as char),
            // UTF-8 bleibt lesbar, alles andere als \xNN
            _ => o.push_str(&format!("\\x{c:02x}")),
        }
    }
    o.push('"');
    o
}

pub fn redis_rdb(dbc: &Db, job: &Job, tables: &[&TableInfo], target: &std::path::Path) -> Res<()> {
    let file = std::fs::File::create(target).map_err(io)?;
    let mut w = rdb::Writer::new(std::io::BufWriter::new(file)).map_err(io)?;
    for t in tables {
        *job.progress.table.lock().unwrap() = t.name.clone();
        let mut n = 0u64;
        rows_of(dbc, &job.db, &t.name, &job.progress, &mut |cols, vals| {
            n += 1;
            let key = redis_key(t, vals, n);
            w.entry(&rdb::Entry { db: 0, key: key.into_bytes(), expire_ms: None, item: rdb::Item::Hash(redis_fields(cols, vals)) }).map_err(io)
        })?;
    }
    w.finish().map_err(io)?;
    Ok(())
}

pub fn redis_commands(dbc: &Db, job: &Job, tables: &[&TableInfo], w: &mut dyn Write) -> Res<()> {
    for t in tables {
        *job.progress.table.lock().unwrap() = t.name.clone();
        let mut n = 0u64;
        rows_of(dbc, &job.db, &t.name, &job.progress, &mut |cols, vals| {
            n += 1;
            let key = redis_key(t, vals, n);
            let fields = redis_fields(cols, vals);
            if fields.is_empty() {
                return Ok(());
            }
            let args: Vec<String> = fields.iter().flat_map(|(k, v)| [redis_quote(k), redis_quote(v)]).collect();
            writeln!(w, "HSET {} {}", redis_quote(key.as_bytes()), args.join(" ")).map_err(io)
        })?;
    }
    Ok(())
}

pub fn redis_server(dbc: &Db, job: &Job, tables: &[&TableInfo], conf: &RedisConf) -> Res<()> {
    let mut push = super::import::RedisPush::connect(conf)?;
    let mut cmds: Vec<Vec<Vec<u8>>> = Vec::new();
    for t in tables {
        *job.progress.table.lock().unwrap() = t.name.clone();
        let mut n = 0u64;
        rows_of(dbc, &job.db, &t.name, &job.progress, &mut |cols, vals| {
            n += 1;
            let fields = redis_fields(cols, vals);
            if fields.is_empty() {
                return Ok(());
            }
            let key = redis_key(t, vals, n);
            if job.replace {
                cmds.push(vec![b"DEL".to_vec(), key.clone().into_bytes()]);
            }
            let mut c = vec![b"HSET".to_vec(), key.into_bytes()];
            for (k, v) in fields {
                c.push(k);
                c.push(v);
            }
            cmds.push(c);
            if cmds.len() >= 500 {
                push.run(&std::mem::take(&mut cmds))?;
            }
            Ok(())
        })?;
    }
    push.run(&cmds)
}

