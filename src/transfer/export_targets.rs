fn pg_ident(s: &str) -> String {
    format!("\"{}\"", s.replace('"', "\"\""))
}

/// Art einer Spalte beim Schreiben der Werte
#[derive(Clone, Copy, PartialEq, Debug)]
pub enum PgKind {
    Number,
    Bytea,
    Date,
    Text,
}

/// PostgreSQL-Typ zu einem MariaDB-Spaltentyp
pub fn pg_type(c: &ColumnInfo) -> (String, PgKind) {
    let t = c.col_type.to_lowercase();
    let base = t.split(['(', ' ']).next().unwrap_or("");
    let args = t.split_once('(').and_then(|(_, r)| r.split_once(')')).map(|(a, _)| a.to_string()).unwrap_or_default();
    let unsigned = t.contains("unsigned");
    let auto = c.extra.to_lowercase().contains("auto_increment");
    let ident = |ty: &str| if auto { format!("{ty} GENERATED BY DEFAULT AS IDENTITY") } else { ty.to_string() };
    match base {
        "tinyint" | "smallint" | "year" => (ident("SMALLINT"), PgKind::Number),
        "mediumint" | "int" | "integer" => (ident("INTEGER"), PgKind::Number),
        "bigint" if unsigned => ("NUMERIC(20,0)".into(), PgKind::Number),
        "bigint" => (ident("BIGINT"), PgKind::Number),
        "decimal" | "numeric" => (format!("NUMERIC({})", if args.is_empty() { "10,0".into() } else { args }), PgKind::Number),
        "float" => ("REAL".into(), PgKind::Number),
        "double" | "real" => ("DOUBLE PRECISION".into(), PgKind::Number),
        "char" => (format!("CHAR({})", if args.is_empty() { "1".into() } else { args }), PgKind::Text),
        "varchar" => (format!("VARCHAR({})", if args.is_empty() { "255".into() } else { args }), PgKind::Text),
        "tinyblob" | "blob" | "mediumblob" | "longblob" | "binary" | "varbinary" => ("BYTEA".into(), PgKind::Bytea),
        "date" => ("DATE".into(), PgKind::Date),
        "datetime" | "timestamp" => ("TIMESTAMP".into(), PgKind::Date),
        "time" => ("TIME".into(), PgKind::Text),
        "json" => ("JSON".into(), PgKind::Text),
        _ => ("TEXT".into(), PgKind::Text),
    }
}

/// Wert als PostgreSQL-Literal
pub fn pg_literal(kind: PgKind, v: &Value) -> String {
    let Some(s) = (match v {
        Value::NULL => None,
        Value::Bytes(b) => match (std::str::from_utf8(b), kind) {
            (_, PgKind::Bytea) => Some(format!("\\x{}", b.iter().map(|x| format!("{x:02x}")).collect::<String>())),
            (Ok(s), _) => Some(s.to_string()),
            (Err(_), _) => Some(String::from_utf8_lossy(b).into_owned()),
        },
        other => crate::db::value_to_string(other),
    }) else {
        return "NULL".into();
    };
    match kind {
        PgKind::Number if valid_number(&s) => s,
        PgKind::Number => format!("'{}'", s.replace('\'', "''")),
        // Nullwerte wie 0000-00-00 kennt PostgreSQL nicht
        PgKind::Date if s.starts_with("0000-00-00") => "NULL".into(),
        _ => format!("'{}'", s.replace('\'', "''").replace('\0', "")),
    }
}

/// Anweisung zum Anlegen einer Tabelle fuer PostgreSQL
pub fn pg_create(t: &TableInfo, schema: &Schema) -> (String, Vec<PgKind>) {
    let mut kinds = Vec::new();
    let mut defs: Vec<String> = t
        .columns
        .iter()
        .map(|c| {
            let (ty, kind) = pg_type(c);
            kinds.push(kind);
            let identity = ty.contains("IDENTITY");
            format!("{} {}{}", pg_ident(&c.name), ty, if !c.nullable || identity { " NOT NULL" } else { "" })
        })
        .collect();
    let pk = t.pk_columns();
    if !pk.is_empty() {
        defs.push(format!("PRIMARY KEY ({})", pk.iter().map(|c| pg_ident(c)).collect::<Vec<_>>().join(", ")));
    }
    for (tn, cols) in &schema.unique_keys {
        if *tn == t.name && *cols != pk && !cols.is_empty() {
            defs.push(format!("UNIQUE ({})", cols.iter().map(|c| pg_ident(c)).collect::<Vec<_>>().join(", ")));
        }
    }
    (format!("CREATE TABLE {} (\n  {}\n)", pg_ident(&t.name), defs.join(",\n  ")), kinds)
}

/// Fremdschluessel und Zaehler zuruecksetzen, nachdem alle Daten da sind
pub fn pg_finish(schema: &Schema, tables: &[&TableInfo]) -> Vec<String> {
    let names: Vec<&str> = tables.iter().map(|t| t.name.as_str()).collect();
    let mut out = Vec::new();
    for fk in schema.fks.iter().filter(|f| names.contains(&f.table.as_str()) && names.contains(&f.ref_table.as_str())) {
        fn rule(r: &str) -> &str {
            if matches!(r, "CASCADE" | "SET NULL" | "RESTRICT" | "NO ACTION" | "SET DEFAULT") { r } else { "NO ACTION" }
        }
        out.push(format!(
            "ALTER TABLE {} ADD FOREIGN KEY ({}) REFERENCES {} ({}) ON DELETE {} ON UPDATE {}",
            pg_ident(&fk.table),
            fk.columns.iter().map(|c| pg_ident(c)).collect::<Vec<_>>().join(", "),
            pg_ident(&fk.ref_table),
            fk.ref_columns.iter().map(|c| pg_ident(c)).collect::<Vec<_>>().join(", "),
            rule(&fk.on_delete),
            rule(&fk.on_update)
        ));
    }
    for t in tables {
        for c in t.columns.iter().filter(|c| c.extra.to_lowercase().contains("auto_increment")) {
            out.push(format!(
                "SELECT setval(pg_get_serial_sequence('{}', '{}'), COALESCE((SELECT MAX({}) FROM {}), 0) + 1, false)",
                pg_ident(&t.name).replace('\'', "''"),
                c.name.replace('\'', "''"),
                pg_ident(&c.name),
                pg_ident(&t.name)
            ));
        }
    }
    out
}

/// Gemeinsamer Ablauf fuer PostgreSQL-Skript und -Server: `emit` bekommt jede Anweisung.
fn pg_run(dbc: &Db, job: &Job, tables: &[&TableInfo], schema: &Schema, drop_first: bool, emit: &mut dyn FnMut(&str) -> Res<()>) -> Res<()> {
    for t in tables {
        *job.progress.table.lock().unwrap() = t.name.clone();
        let (create, kinds) = pg_create(t, schema);
        if drop_first {
            emit(&format!("DROP TABLE IF EXISTS {} CASCADE", pg_ident(&t.name)))?;
        }
        emit(&create)?;
        if !job.with_data {
            continue;
        }
        let cols = t.columns.iter().map(|c| pg_ident(&c.name)).collect::<Vec<_>>().join(", ");
        let mut batch: Vec<String> = Vec::new();
        let flush = |batch: &mut Vec<String>, emit: &mut dyn FnMut(&str) -> Res<()>| -> Res<()> {
            if batch.is_empty() {
                return Ok(());
            }
            let sql = format!("INSERT INTO {} ({cols}) VALUES\n  {}", pg_ident(&t.name), batch.join(",\n  "));
            batch.clear();
            emit(&sql)
        };
        rows_of(dbc, &job.db, &t.name, &job.progress, &mut |_, vals| {
            batch.push(format!("({})", vals.iter().zip(&kinds).map(|(v, k)| pg_literal(*k, v)).collect::<Vec<_>>().join(", ")));
            if batch.len() >= 200 {
                flush(&mut batch, emit)?;
            }
            Ok(())
        })?;
        flush(&mut batch, emit)?;
    }
    for s in pg_finish(schema, tables) {
        emit(&s)?;
    }
    Ok(())
}

/// PostgreSQL-Skript in eine Datei schreiben
pub fn pg_script(dbc: &Db, job: &Job, tables: &[&TableInfo], schema: &Schema, w: &mut dyn Write) -> Res<()> {
    writeln!(w, "-- EasyMySQL export for PostgreSQL\n-- Database: {}\n", job.db).map_err(io)?;
    pg_run(dbc, job, tables, schema, false, &mut |sql| write!(w, "{sql};\n\n").map_err(io))
}

/// Direkt auf einen PostgreSQL-Server uebertragen
pub fn pg_server(dbc: &Db, job: &Job, tables: &[&TableInfo], schema: &Schema, link: &Link) -> Res<()> {
    let mut c = crate::transfer::import::pg_connect(link, Some(&link.conf.database))?;
    let mut tx = c.transaction().map_err(|e| e.to_string())?;
    pg_run(dbc, job, tables, schema, job.replace, &mut |sql| tx.batch_execute(sql).map_err(|e| format!("{e}: {}", sql.chars().take(120).collect::<String>())))?;
    tx.commit().map_err(|e| e.to_string())
}

