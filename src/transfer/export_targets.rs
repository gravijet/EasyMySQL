        let tables = import::scan(&src, &AtomicBool::new(false)).unwrap();
        assert_eq!(tables.len(), 1);
        assert_eq!(tables[0].name, "redis_hashes");
        assert_eq!(tables[0].rows, 14, "{:?}", tables[0]);

        // --- Redis-Server
        let conf = ServerConf::new(6399);
        let link = conf.open().unwrap();
        let rc = RedisConf { host: "127.0.0.1".into(), port: 6399, db: 0, link: Some(link), ..Default::default() };
        crate::transfer::export::run(&dbc, &job("xt_src", Format::Sql, std::path::PathBuf::new(), Some(Server::Redis(rc.clone())))).unwrap();
        let src = Source::Redis(rc);
        let tables = import::scan(&src, &AtomicBool::new(false)).unwrap();
        assert!(tables.iter().any(|t| t.name == "redis_hashes"));

        // --- PostgreSQL-Server
        let mut pg = ServerConf::new(5432);
        pg.user = "tester".into();
        pg.password = "pw123".into();
        pg.database = "xt".into();
        let link = pg.open().unwrap();
        crate::transfer::export::run(&dbc, &job("xt_src", Format::Sql, std::path::PathBuf::new(), Some(Server::Postgres(link.clone())))).unwrap();
        // zurueck nach MariaDB
        let src = Source::Postgres(link);
        let p = Progress::default();
        let tables = import::scan(&src, &AtomicBool::new(false)).unwrap();
        assert_eq!(tables.len(), 2, "{tables:?}");
        let n = write::run(&dbc, &src, &tables, &Options { database: "xt_back".into(), create_db: true, replace: true }, &p).unwrap();
        assert_eq!(n, 4, "{:?}", p.log.lock().unwrap());
        let rows = dbc.rows("SELECT name, preis, seit, HEX(bild), notiz FROM xt_back.kunde ORDER BY id", ()).unwrap();
        assert_eq!(rows[0], vec![Some("Müller; O'Neil".into()), Some("9.50".into()), Some("2024-01-02 03:04:05".into()), Some("FF00".into()), Some("a\nb".into())], "{:?}", p.log.lock().unwrap());
        assert_eq!(dbc.schema("xt_back").unwrap().fks.len(), 1);

        // --- PostgreSQL-Skript und MongoDB-Zeilen
        let r = crate::transfer::export::run(&dbc, &job("xt_src", Format::PgSql, dir.join("a.sql"), None)).unwrap();
        let sql = std::fs::read_to_string(r).unwrap();
        assert!(sql.contains("CREATE TABLE \"kunde\"") && sql.contains("INSERT INTO \"bestellung\"") && sql.contains("FOREIGN KEY"));
        let r = crate::transfer::export::run(&dbc, &job("xt_src", Format::Mongo, dir.join("m"), None)).unwrap();
        let line = std::fs::read_to_string(std::path::Path::new(&r).join("kunde.jsonl")).unwrap();
        assert!(line.lines().next().unwrap().contains("\"$date\""), "{line}");
        let r = crate::transfer::export::run(&dbc, &job("xt_src", Format::RedisCmds, dir.join("a.redis"), None)).unwrap();
        assert!(std::fs::read_to_string(r).unwrap().contains("HSET \"kunde:1\""));

        // --- anderer MariaDB-Server (hier derselbe) und zurueck
        let mut my = ServerConf::new(3306);
        my.user = "root".into();
        my.database = "xt_copy".into();
        let link = my.open().unwrap();
        crate::transfer::export::run(&dbc, &job("xt_src", Format::Sql, std::path::PathBuf::new(), Some(Server::Mysql(link.clone())))).unwrap();
        let rows = dbc.rows("SELECT COUNT(*) FROM xt_copy.bestellung", ()).unwrap();
        assert_eq!(rows[0][0].as_deref(), Some("2"));
        let src = Source::Mysql(link);
        let tables = import::scan(&src, &AtomicBool::new(false)).unwrap();
        assert!(tables.iter().all(|t| t.ddl.is_some()));
        for d in ["xt_src", "xt_back", "xt_copy"] {
            let _ = c.query_drop(format!("DROP DATABASE IF EXISTS {d}"));
        }
        let _ = std::fs::remove_dir_all(&dir);
