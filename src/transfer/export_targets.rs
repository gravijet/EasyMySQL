// Anderer MariaDB-/MySQL-Server

pub fn mysql_server(dbc: &Db, job: &Job, tables: &[&TableInfo], link: &Link) -> Res<()> {
    let target_db = if link.conf.database.is_empty() { job.db.clone() } else { link.conf.database.clone() };
    let mut c = crate::transfer::import::mysql_connect(link, None)?;
    c.query_drop(format!("CREATE DATABASE IF NOT EXISTS {} CHARACTER SET utf8mb4", q(&target_db))).map_err(err_text)?;
    c.query_drop(format!("USE {}", q(&target_db))).map_err(err_text)?;
    c.query_drop("SET SESSION foreign_key_checks = 0, unique_checks = 0").map_err(err_text)?;
    let existing: Vec<String> = c.query::<String, _>("SHOW TABLES").map_err(err_text)?.into_iter().map(|t| t.to_lowercase()).collect();
    for t in tables {
        *job.progress.table.lock().unwrap() = t.name.clone();
        if existing.contains(&t.name.to_lowercase()) {
            if !job.replace {
                job.progress.log.lock().unwrap().push((true, crate::tr_format!("{}: gibt es schon – übersprungen.", "{}: already exists — skipped.", t.name)));
                continue;
            }
            c.query_drop(format!("DROP TABLE {}", q(&t.name))).map_err(err_text)?;
        }
        let ddl = dbc.create_statement(&job.db, &t.name)?;
        c.query_drop(ddl).map_err(|e| format!("{}: {}", t.name, err_text(e)))?;
        if !job.with_data {
            continue;
        }
        let n = t.columns.len().max(1);
        let per = (60_000 / n).clamp(1, 500);
        let marks = format!("({})", vec!["?"; n].join(","));
        let names = t.columns.iter().map(|c| q(&c.name)).collect::<Vec<_>>().join(",");
        let mut batch: Vec<Value> = Vec::new();
        let mut rows = 0usize;
        let flush = |c: &mut mysql::Conn, batch: &mut Vec<Value>, rows: usize| -> Res<()> {
            if rows == 0 {
                return Ok(());
            }
            let sql = format!("INSERT INTO {} ({names}) VALUES {}", q(&t.name), vec![marks.clone(); rows].join(","));
            c.exec_drop(sql, Params::Positional(std::mem::take(batch))).map_err(|e| format!("{}: {}", t.name, err_text(e)))
        };
        c.query_drop("START TRANSACTION").map_err(err_text)?;
        let r = rows_of(dbc, &job.db, &t.name, &job.progress, &mut |_, vals| {
            batch.extend(vals.iter().cloned());
            rows += 1;
            if rows == per {
                flush(&mut c, &mut batch, rows)?;
                rows = 0;
            }
            Ok(())
        });
        let r = r.and_then(|_| flush(&mut c, &mut batch, rows));
        c.query_drop(if r.is_ok() { "COMMIT" } else { "ROLLBACK" }).map_err(err_text)?;
        r?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(name: &str, ty: &str, extra: &str) -> ColumnInfo {
        ColumnInfo { name: name.into(), col_type: ty.into(), nullable: true, extra: extra.into(), ..Default::default() }
    }

    #[test]
    fn postgres_types_and_literals() {
        assert_eq!(pg_type(&col("a", "int(11) unsigned", "")).0, "INTEGER");
        assert_eq!(pg_type(&col("a", "int(11)", "auto_increment")).0, "INTEGER GENERATED BY DEFAULT AS IDENTITY");
        assert_eq!(pg_type(&col("a", "decimal(10,2)", "")), ("NUMERIC(10,2)".into(), PgKind::Number));
        assert_eq!(pg_type(&col("a", "varchar(40)", "")).0, "VARCHAR(40)");
        assert_eq!(pg_type(&col("a", "longtext", "")).0, "TEXT");
        assert_eq!(pg_type(&col("a", "datetime", "")), ("TIMESTAMP".into(), PgKind::Date));
        assert_eq!(pg_type(&col("a", "blob", "")), ("BYTEA".into(), PgKind::Bytea));
        assert_eq!(pg_type(&col("a", "enum('a','b')", "")).0, "TEXT");
        assert_eq!(pg_literal(PgKind::Text, &Value::Bytes(b"O'Neil".to_vec())), "'O''Neil'");
        assert_eq!(pg_literal(PgKind::Number, &Value::Int(5)), "5");
        assert_eq!(pg_literal(PgKind::Number, &Value::NULL), "NULL");
        assert_eq!(pg_literal(PgKind::Bytea, &Value::Bytes(vec![255, 0])), "'\\xff00'");
        assert_eq!(pg_literal(PgKind::Date, &Value::Bytes(b"0000-00-00".to_vec())), "NULL");
        assert_eq!(pg_ident("a\"b"), "\"a\"\"b\"");
    }

    #[test]
    fn postgres_create_with_keys() {
        let mut id = col("id", "int(11)", "auto_increment");
        id.key = "PRI".into();
        id.nullable = false;
        let t = TableInfo { name: "kunde".into(), columns: vec![id, col("name", "varchar(20)", "")], ..Default::default() };
        let schema = Schema { tables: vec![t.clone()], ..Default::default() };
        let (sql, kinds) = pg_create(&t, &schema);
        assert!(sql.starts_with("CREATE TABLE \"kunde\" ("));
        assert!(sql.contains("\"id\" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL"));
        assert!(sql.contains("PRIMARY KEY (\"id\")"));
        assert_eq!(kinds, vec![PgKind::Number, PgKind::Text]);
        assert!(pg_finish(&schema, &[&t])[0].contains("setval"));
    }

    #[test]
    fn redis_quoting_and_mongo_values() {
        assert_eq!(redis_quote(b"a \"b\"\n\\"), "\"a \\\"b\\\"\\n\\\\\"");
        assert_eq!(redis_quote(&[0xC3, 0x9C]), "\"\\xc3\\x9c\"");
        assert_eq!(mongo_value(T::MYSQL_TYPE_LONG, &Value::Bytes(b"42".to_vec())), "42");
        assert_eq!(mongo_value(T::MYSQL_TYPE_DATETIME, &Value::Bytes(b"2024-01-02 03:04:05".to_vec())), "{\"$date\":\"2024-01-02T03:04:05Z\"}");
        assert_eq!(mongo_value(T::MYSQL_TYPE_VAR_STRING, &Value::NULL), "null");
        let mut pk = col("id", "int", "");
        pk.key = "PRI".into();
        let t = TableInfo { name: "t".into(), columns: vec![pk, col("x", "int", "")], ..Default::default() };
        assert_eq!(redis_key(&t, &[Value::Int(7), Value::Int(1)], 3), "t:7");
        let t2 = TableInfo { name: "t".into(), columns: vec![col("x", "int", "")], ..Default::default() };
        assert_eq!(redis_key(&t2, &[Value::Int(1)], 3), "t:3");
    }
}

