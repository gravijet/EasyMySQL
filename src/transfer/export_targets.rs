// MongoDB (eine Datei mit JSON-Zeilen je Tabelle)

fn mongo_value(t: T, v: &Value) -> String {
    let Some(s) = text(v) else { return "null".into() };
    match t {
        T::MYSQL_TYPE_DATETIME | T::MYSQL_TYPE_TIMESTAMP | T::MYSQL_TYPE_DATETIME2 | T::MYSQL_TYPE_TIMESTAMP2 if !s.starts_with("0000") => {
            format!("{{\"$date\":{}}}", serde_json::Value::String(format!("{}Z", s.replacen(' ', "T", 1))))
        }
        t if is_number(t) && valid_number(&s) => s,
        T::MYSQL_TYPE_JSON if serde_json::from_str::<serde_json::Value>(&s).is_ok() => s,
        _ => serde_json::Value::String(s).to_string(),
    }
}

pub fn mongo_lines(dbc: &Db, job: &Job, t: &TableInfo, w: &mut dyn Write) -> Res<()> {
    *job.progress.table.lock().unwrap() = t.name.clone();
    rows_of(dbc, &job.db, &t.name, &job.progress, &mut |cols, vals| {
        let fields: Vec<String> = cols.iter().zip(vals).filter(|(_, v)| !matches!(v, Value::NULL)).map(|(c, v)| format!("{}:{}", serde_json::Value::String(c.name_str().into_owned()), mongo_value(c.column_type(), v))).collect();
        writeln!(w, "{{{}}}", fields.join(",")).map_err(io)
    })
}

